
create table if not exists draft.reality_motif_registry (
  motif_id bigint generated by default as identity primary key,
  motif_key text not null unique,
  structure_version text not null,
  canonical_signature text not null,
  edge_count integer not null,
  node_count integer not null,
  motif_status text not null default 'candidate',
  notes text,
  metadata jsonb not null default '{}'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reality_motif_registry_edge_count_check check (edge_count between 2 and 5),
  unique(structure_version,canonical_signature)
);

comment on table draft.reality_motif_registry is
'Registry of label-stripped recurring graph structures recovered from Reality Alignment graphs. A motif is structural form, not an interpretation or domain concept.';

create table if not exists draft.reality_motif_instances (
  motif_instance_id bigint generated by default as identity primary key,
  motif_id bigint not null references draft.reality_motif_registry(motif_id)
    on update cascade on delete cascade,
  occurrence_id bigint not null references draft.reality_occurrences(occurrence_id)
    on update cascade on delete cascade,
  instance_key text not null unique,
  independence_key text not null,
  edge_count integer not null,
  node_count integer not null,
  edge_keys text[] not null,
  node_keys text[] not null,
  coordinate_groups text[] not null default '{}'::text[],
  witness_keys text[] not null default '{}'::text[],
  role_signature text,
  structure jsonb not null,
  instance_status text not null default 'materialized',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(occurrence_id,edge_keys)
);

comment on table draft.reality_motif_instances is
'Concrete appearances of a structural motif inside one Reality Occurrence. Native labels are recoverable through edge/node references but are excluded from the motif canonical signature.';

create index if not exists reality_motif_instances_motif_idx
on draft.reality_motif_instances(motif_id,independence_key);

create index if not exists reality_motif_instances_occurrence_idx
on draft.reality_motif_instances(occurrence_id);

create table if not exists draft.reality_motif_compositions (
  motif_composition_id bigint generated by default as identity primary key,
  parent_motif_id bigint not null references draft.reality_motif_registry(motif_id)
    on update cascade on delete cascade,
  child_motif_id bigint not null references draft.reality_motif_registry(motif_id)
    on update cascade on delete cascade,
  composition_role text not null,
  composition_status text not null default 'candidate',
  evidence_count integer not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(parent_motif_id,child_motif_id,composition_role)
);

comment on table draft.reality_motif_compositions is
'Composition graph between recovered motifs. Populated only when larger recurring structures can be shown to contain or compose smaller motifs.';

