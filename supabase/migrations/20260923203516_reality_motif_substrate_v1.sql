create or replace view intelligence.v_reality_alignment_graph_edges_v1
with (security_invoker=true)
as
with counts as (
  select
    s.alignment_segment_id,
    count(*) filter(where m.side='reality')::integer reality_member_count,
    count(*) filter(where m.side='witness')::integer witness_member_count
  from draft.reality_alignment_segments s
  join draft.reality_alignment_members m using(alignment_segment_id)
  group by s.alignment_segment_id
)
select
  s.occurrence_id,
  o.occurrence_key,
  coalesce(o.metadata->>'independenceKey',o.occurrence_key) independence_key,
  'member:'||m.alignment_member_id::text edge_key,
  'reality_touch'::text edge_class,
  'coordinate:'||c.occurrence_coordinate_id::text source_node_key,
  'coordinate'::text source_node_class,
  'coordinate:'||d.dimension_family||':'||c.coordinate_role source_structural_type,
  'alignment:'||s.alignment_segment_id::text target_node_key,
  'alignment'::text target_node_class,
  'alignment:r'||ct.reality_member_count::text||':w'||ct.witness_member_count::text target_structural_type,
  'touch:'||d.dimension_family||':'||c.coordinate_role edge_structural_type,
  m.member_role,
  c.coordinate_group_key,
  c.dimension_key,
  d.dimension_family,
  null::text witness_key,
  null::text object_type,
  null::text object_id,
  s.alignment_kind,
  s.relation_type,
  m.alignment_member_id
from draft.reality_alignment_members m
join draft.reality_alignment_segments s using(alignment_segment_id)
join draft.reality_occurrences o using(occurrence_id)
join counts ct using(alignment_segment_id)
join draft.reality_occurrence_coordinates c
  on c.occurrence_coordinate_id=m.occurrence_coordinate_id
join draft.reality_query_dimension_registry d using(dimension_key)
where m.side='reality'

union all
select
  s.occurrence_id,
  o.occurrence_key,
  coalesce(o.metadata->>'independenceKey',o.occurrence_key),
  'member:'||m.alignment_member_id::text,
  'witness_touch',
  'alignment:'||s.alignment_segment_id::text,
  'alignment',
  'alignment:r'||ct.reality_member_count::text||':w'||ct.witness_member_count::text,
  'witness:'||m.witness_key||':'||m.object_type||':'||m.object_id,
  'witness_object',
  'witness_object',
  'touch:witness_object',
  m.member_role,
  null,
  null,
  null,
  m.witness_key,
  m.object_type,
  m.object_id,
  s.alignment_kind,
  s.relation_type,
  m.alignment_member_id
from draft.reality_alignment_members m
join draft.reality_alignment_segments s using(alignment_segment_id)
join draft.reality_occurrences o using(occurrence_id)
join counts ct using(alignment_segment_id)
where m.side='witness';

comment on view intelligence.v_reality_alignment_graph_edges_v1 is
'Label-strippable graph projection of Reality Alignment. Coordinate values, source labels, and native object names are absent from structural node/edge types; native references remain available separately for instance recovery.';

revoke all on intelligence.v_reality_alignment_graph_edges_v1 from anon,authenticated;
