BEGIN;
-- Noel-private longitudinal casework; no personal or clinical content in source.
CREATE TABLE practice.encounter_notes_v1 (
  note_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL REFERENCES practice.people(person_id) ON DELETE RESTRICT,
  session_id bigint REFERENCES practice.sessions(session_id) ON DELETE RESTRICT,
  occurred_on date NOT NULL,
  exact_language text NOT NULL CHECK (length(btrim(exact_language)) > 0),
  reporter_kind text NOT NULL DEFAULT 'practitioner' CHECK
    (reporter_kind IN ('practitioner','participant','third_party','historical_source','unknown')),
  source_kind text NOT NULL DEFAULT 'narrative',
  source_locator text,
  author_ref text,
  review_status text NOT NULL DEFAULT 'unstructured' CHECK
    (review_status IN ('unstructured','in_review','structured','superseded')),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE practice.encounter_observation_links_v1 (
  link_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id bigint NOT NULL REFERENCES practice.sessions(session_id) ON DELETE RESTRICT,
  body_observation_id bigint NOT NULL REFERENCES practice.body_observations(body_observation_id) ON DELETE RESTRICT,
  intervention_id bigint REFERENCES practice.interventions(intervention_id) ON DELETE RESTRICT,
  outcome_id bigint REFERENCES practice.outcomes(outcome_id) ON DELETE RESTRICT,
  source_note_id bigint REFERENCES practice.encounter_notes_v1(note_id) ON DELETE RESTRICT,
  link_basis text NOT NULL CHECK (link_basis IN
    ('source_explicit','practitioner_report','participant_report','retrospective_hypothesis')),
  exact_supporting_language text NOT NULL CHECK (length(btrim(exact_supporting_language)) > 0),
  review_status text NOT NULL DEFAULT 'proposed' CHECK
    (review_status IN ('proposed','source_confirmed','contested','rejected','superseded')),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (intervention_id IS NOT NULL OR outcome_id IS NOT NULL)
);
COMMENT ON TABLE practice.encounter_notes_v1 IS
'Exact private narrative, never clinical verification. Keep source and author; do not silently reinterpret.';
COMMENT ON TABLE practice.encounter_observation_links_v1 IS
'Explicit source relationship; source_confirmed never means causation, clinical efficacy or medical necessity.';
CREATE FUNCTION practice.validate_case_note_v1() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,practice AS $$
BEGIN
 IF NEW.session_id IS NOT NULL AND NOT EXISTS
  (SELECT 1 FROM practice.sessions s WHERE s.session_id=NEW.session_id AND s.person_id=NEW.person_id)
 THEN RAISE EXCEPTION 'Person/session mismatch'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER validate_case_note_v1 BEFORE INSERT OR UPDATE
ON practice.encounter_notes_v1 FOR EACH ROW
EXECUTE FUNCTION practice.validate_case_note_v1();

CREATE FUNCTION practice.validate_observation_link_v1() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,practice AS $$
DECLARE v_person_id bigint;
BEGIN
 SELECT person_id INTO v_person_id FROM practice.sessions WHERE session_id=NEW.session_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown encounter'; END IF;
 IF NOT EXISTS (SELECT 1 FROM practice.body_observations
   WHERE body_observation_id=NEW.body_observation_id AND session_id=NEW.session_id)
 THEN RAISE EXCEPTION 'Observation belongs to another encounter'; END IF;
 IF NEW.intervention_id IS NOT NULL AND NOT EXISTS
   (SELECT 1 FROM practice.interventions WHERE intervention_id=NEW.intervention_id AND session_id=NEW.session_id)
 THEN RAISE EXCEPTION 'Intervention belongs to another encounter'; END IF;
 IF NEW.outcome_id IS NOT NULL AND NOT EXISTS
   (SELECT 1 FROM practice.outcomes WHERE outcome_id=NEW.outcome_id AND session_id=NEW.session_id)
 THEN RAISE EXCEPTION 'Outcome belongs to another encounter'; END IF;
 IF NEW.source_note_id IS NOT NULL AND NOT EXISTS
   (SELECT 1 FROM practice.encounter_notes_v1
    WHERE note_id=NEW.source_note_id AND person_id=v_person_id
      AND (session_id IS NULL OR session_id=NEW.session_id))
 THEN RAISE EXCEPTION 'Source note belongs to another person or encounter'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER validate_observation_link_v1 BEFORE INSERT OR UPDATE
ON practice.encounter_observation_links_v1 FOR EACH ROW
EXECUTE FUNCTION practice.validate_observation_link_v1();
CREATE INDEX encounter_note_person_day_v1_idx
 ON practice.encounter_notes_v1(person_id,occurred_on,note_id);
CREATE INDEX encounter_link_observation_v1_idx
 ON practice.encounter_observation_links_v1(body_observation_id,review_status);
CREATE INDEX encounter_link_session_v1_idx
 ON practice.encounter_observation_links_v1(session_id);
-- Observation-granular view: never pair all actions and observations
-- merely because they share a session or body region.
CREATE VIEW practice.v_person_body_episode_history_v1 WITH (security_invoker=true) AS
SELECT s.person_id,s.session_id,s.session_date,s.historical,
 b.body_observation_id,b.region_key,b.side,b.observation_type,
 b.normalized_state,b.raw_language AS observation_language,
 b.reported_by,b.intensity_value,b.intensity_scale,b.observed_at,
 COALESCE((SELECT jsonb_agg(DISTINCT jsonb_build_object(
  'intervention_id',i.intervention_id,'practice_label',i.practice_label,
  'intervention_type',i.intervention_type,'exact_words',i.exact_words,
  'link_basis',l.link_basis,'support',l.exact_supporting_language))
  FROM practice.encounter_observation_links_v1 l
  JOIN practice.interventions i ON i.intervention_id=l.intervention_id
  WHERE l.body_observation_id=b.body_observation_id
    AND l.review_status='source_confirmed'
    AND l.intervention_id IS NOT NULL),'[]'::jsonb) AS linked_actions,
 COALESCE((SELECT jsonb_agg(DISTINCT jsonb_build_object(
  'outcome_id',o.outcome_id,'outcome_type',o.outcome_type,
  'outcome_text',o.outcome_text,'reported_by',o.reported_by,
  'durability',o.durability,
  'source_relationship',CASE WHEN o.body_observation_id=b.body_observation_id
    THEN 'original_explicit_fk' ELSE l.link_basis END))
  FROM practice.outcomes o
  LEFT JOIN practice.encounter_observation_links_v1 l
    ON l.outcome_id=o.outcome_id
    AND l.body_observation_id=b.body_observation_id
    AND l.review_status='source_confirmed'
  WHERE o.body_observation_id=b.body_observation_id OR l.link_id IS NOT NULL),'[]'::jsonb) AS linked_afterward_reports,
 COALESCE((SELECT jsonb_agg(DISTINCT jsonb_build_object(
  'source_kind',ss.source_kind,'source_reference',ss.source_reference))
 FROM practice.session_sources ss WHERE ss.session_id=s.session_id),'[]'::jsonb) AS session_sources
FROM practice.sessions s JOIN practice.body_observations b ON b.session_id=s.session_id;
CREATE VIEW practice.v_person_body_recurrence_v1 WITH (security_invoker=true) AS
SELECT s.person_id,b.region_key,b.side,b.observation_type,
 lower(btrim(b.normalized_state)) AS normalized_state_key,
 count(*) AS raw_observation_rows,
 count(DISTINCT s.session_date) AS documented_dates,
 min(s.session_date) AS first_documented_date,
 max(s.session_date) AS last_documented_date
FROM practice.sessions s JOIN practice.body_observations b ON b.session_id=s.session_id
GROUP BY s.person_id,b.region_key,b.side,b.observation_type,lower(btrim(b.normalized_state));
COMMENT ON VIEW practice.v_person_body_recurrence_v1 IS
'Exact category and region, no ear/hearing to ear/pain conflation. Raw rows may include duplicate imports; documented_dates is not an event count.';
CREATE FUNCTION practice.person_body_history_v1(
 p_person_id bigint,p_region_key text DEFAULT NULL,p_normalized_state text DEFAULT NULL)
RETURNS SETOF practice.v_person_body_episode_history_v1
LANGUAGE sql STABLE SECURITY INVOKER SET search_path=pg_catalog,practice AS $$
 SELECT h.* FROM practice.v_person_body_episode_history_v1 h
 WHERE h.person_id=p_person_id AND (p_region_key IS NULL OR h.region_key=p_region_key)
 AND (p_normalized_state IS NULL OR lower(btrim(h.normalized_state))=lower(btrim(p_normalized_state)))
 ORDER BY h.session_date,h.session_id,h.body_observation_id
$$;
-- Private from the outset. No application, participant, Titus or public grants.
ALTER TABLE practice.encounter_notes_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE practice.encounter_observation_links_v1 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE practice.encounter_notes_v1,practice.encounter_observation_links_v1,
 practice.v_person_body_episode_history_v1,practice.v_person_body_recurrence_v1
 FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON FUNCTION practice.validate_case_note_v1(),practice.validate_observation_link_v1(),
 practice.person_body_history_v1(bigint,text,text)
 FROM PUBLIC,anon,authenticated,service_role;
COMMIT;
