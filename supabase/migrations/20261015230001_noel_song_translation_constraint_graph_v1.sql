-- NOEL: Song-led mark translation constraint graph (private, structural proposal).
-- Governance: review-only candidate, not production DDL. Must use generated
-- noel_ migration, disposable production-schema-clone validation, and manual release.
-- Original corpus, mark IDs, founder pools, and steward decisions are untouched.
BEGIN;

-- Every source occurrence retains one canonical mark binding. These edges
-- materialize observed MT -> CATSS Greek LXX word choices, never permissions.
CREATE TABLE draft.noel_mark_lxx_choice_occurrences_v1 (
 choice_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 identity_id text NOT NULL REFERENCES draft.noel_mark_identities(identity_id),
 witness_key text NOT NULL DEFAULT 'mt_noel_current'
   CHECK (witness_key='mt_noel_current'),
 source_token_id text NOT NULL,
 form_id text NOT NULL,
 alignment_segment_id bigint NOT NULL
   REFERENCES core.alignment_segments(alignment_segment_id),
 greek_token_id text NOT NULL,
 greek_lexeme_key text NOT NULL CHECK (length(btrim(greek_lexeme_key))>0),
 greek_surface text,
 source_member_order integer,
 target_member_order integer,
 source_member_role text,
 target_member_role text,
 source_segment_count integer NOT NULL DEFAULT 1 CHECK (source_segment_count>0),
 target_segment_count integer NOT NULL DEFAULT 1 CHECK (target_segment_count>0),
 mapping_scope text NOT NULL DEFAULT 'direct_token'
  CHECK(mapping_scope IN ('direct_token','one_to_many','many_to_one','many_to_many')),
 CHECK (
 (mapping_scope='direct_token' AND source_segment_count=1 AND target_segment_count=1)
 OR (mapping_scope='one_to_many' AND source_segment_count=1 AND target_segment_count>1)
 OR (mapping_scope='many_to_one' AND source_segment_count>1 AND target_segment_count=1)
 OR (mapping_scope='many_to_many' AND source_segment_count>1 AND target_segment_count>1)
 ),
 greek_member_function text NOT NULL DEFAULT 'unassessed'
  CHECK(greek_member_function IN ('unassessed','content_candidate',
   'connector_candidate','content_reviewed','connector_reviewed')),
 evidence_quality text NOT NULL DEFAULT 'direct_unflagged'
   CHECK (evidence_quality IN
    ('direct_unflagged','phrase_candidate','variant_review','unresolved')),
 provenance_note text NOT NULL DEFAULT
   'Observed translation evidence only; never a source-semantic ruling.',
 recorded_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (witness_key,source_token_id,alignment_segment_id,greek_token_id),
 UNIQUE (choice_id,identity_id)
);
CREATE INDEX noel_mark_lxx_choice_by_identity_lex_v1
 ON draft.noel_mark_lxx_choice_occurrences_v1(identity_id,greek_lexeme_key);
CREATE INDEX noel_mark_lxx_choice_by_greek_identity_v1
 ON draft.noel_mark_lxx_choice_occurrences_v1(greek_lexeme_key,identity_id);
CREATE INDEX noel_mark_lxx_choice_by_token_v1
 ON draft.noel_mark_lxx_choice_occurrences_v1(source_token_id);

-- Song is first: each actual Song LXX choice stays traceable to its source word.
-- Several Song Greek forms can legitimately coexist until Song-local review.
CREATE TABLE draft.noel_mark_song_anchor_choices_v1 (
 anchor_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 identity_id text NOT NULL REFERENCES draft.noel_mark_identities(identity_id),
 choice_id bigint NOT NULL,
 song_canonical_ref text NOT NULL CHECK(song_canonical_ref LIKE 'Sng %'),
 song_anchor_state text NOT NULL DEFAULT 'attested_song_choice'
   CHECK (song_anchor_state IN
   ('attested_song_choice','sole_direct_song_choice','song_multiple_open',
    'reviewed_song_priority','retracted_alignment')),
 authority_note text NOT NULL DEFAULT
   'Song-priority Greek evidence; not an automatically proved Hebrew operation.',
 recorded_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(choice_id),
 FOREIGN KEY (choice_id,identity_id)
 REFERENCES draft.noel_mark_lxx_choice_occurrences_v1(choice_id,identity_id)
);
CREATE INDEX noel_mark_song_anchors_by_identity_v1
 ON draft.noel_mark_song_anchor_choices_v1(identity_id,song_anchor_state);

-- A translation test is NOT synonymous with a recorded LXX choice. It can be
-- scoped to one identity, one exact form, or one attested occurrence/state.
CREATE TABLE draft.noel_mark_translation_constraints_v1 (
 constraint_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 identity_id text NOT NULL REFERENCES draft.noel_mark_identities(identity_id),
 candidate_greek_lexeme_key text NOT NULL
   CHECK (length(btrim(candidate_greek_lexeme_key))>0),
 scope_kind text NOT NULL DEFAULT 'identity'
   CHECK (scope_kind IN ('identity','form','occurrence','state_transition')),
 scope_ref text NOT NULL CHECK(length(btrim(scope_ref))>0),
 assessment_state text NOT NULL DEFAULT 'unassessed'
   CHECK (assessment_state IN
    ('unassessed','song_preferred','compatible_candidate',
     'context_restricted','elimination_candidate','canon_excluded')),
 before_state text,
 governing_operation text,
 after_state text,
 condition_predicates jsonb NOT NULL DEFAULT '{}'::jsonb
   CHECK(jsonb_typeof(condition_predicates)='object'),
 test_basis text NOT NULL DEFAULT 'Not yet tested against canonical transitions.',
 counterexample_basis text,
 stewardship_decision_id bigint
   REFERENCES draft.noel_reality_decisions(decision_id),
 recorded_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(identity_id,candidate_greek_lexeme_key,scope_kind,scope_ref),
 -- A canonical exclusion is never produced automatically from unequal Greek.
 CHECK (assessment_state<>'canon_excluded' OR
       (stewardship_decision_id IS NOT NULL AND
        length(btrim(coalesce(counterexample_basis,'')))>0 AND
        length(btrim(coalesce(before_state,'')))>0 AND
        length(btrim(coalesce(governing_operation,'')))>0 AND
        length(btrim(coalesce(after_state,'')))>0))
);
CREATE INDEX noel_mark_translation_constraints_by_identity_v1
 ON draft.noel_mark_translation_constraints_v1(identity_id,assessment_state);

-- Evidence is separately inspectable and keeps supporting and defeating
-- canonical occurrences; a constraint cannot bury contrary witnesses.
CREATE TABLE draft.noel_mark_translation_constraint_witnesses_v1 (
 witness_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 constraint_id bigint NOT NULL REFERENCES
   draft.noel_mark_translation_constraints_v1(constraint_id)
   ON DELETE RESTRICT,
 source_witness_key text NOT NULL DEFAULT 'mt_noel_current',
 source_token_id text NOT NULL,
 alignment_segment_id bigint
   REFERENCES core.alignment_segments(alignment_segment_id),
 greek_token_id text,
 canon_reference text NOT NULL CHECK(length(btrim(canon_reference))>0),
 witness_role text NOT NULL CHECK(witness_role IN
   ('song_anchor','lxx_rendering','canon_support',
    'canon_counterexample','scope_boundary','alignment_uncertainty')),
 before_state text,
 operation text,
 after_state text,
 explanation text NOT NULL CHECK(length(btrim(explanation))>0),
 recorded_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX noel_mark_constraint_witnesses_by_constraint_v1
 ON draft.noel_mark_translation_constraint_witnesses_v1(constraint_id,witness_role);
CREATE INDEX noel_mark_constraint_witnesses_by_source_v1
 ON draft.noel_mark_translation_constraint_witnesses_v1(source_token_id);

-- An exclusion is only a steward-reviewed statement about an interpretation,
-- not an automatic deletion of either the Greek or the Hebrew evidence.
-- Insert a proposed test, attach canonical counterexample witnesses, record a
-- specifically scoped decision, THEN change status to canon_excluded.
CREATE FUNCTION draft.noel_mark_translation_permission_guard_v1()
RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path TO ''
AS $guard$
BEGIN
 IF NEW.assessment_state='song_preferred' AND NOT EXISTS (
  SELECT 1 FROM draft.noel_mark_song_anchor_choices_v1 a
  JOIN draft.noel_mark_lxx_choice_occurrences_v1 e ON e.choice_id=a.choice_id
  WHERE a.identity_id=NEW.identity_id
   AND e.greek_lexeme_key=NEW.candidate_greek_lexeme_key
   AND a.song_anchor_state<>'retracted_alignment'
 ) THEN
   RAISE EXCEPTION 'A Song-preferred Greek lexeme must have an attested Song source-token anchor';
 END IF;
 IF NEW.assessment_state='canon_excluded' THEN
  IF NOT EXISTS (
   SELECT 1 FROM draft.noel_reality_decisions d
   WHERE d.decision_id=NEW.stewardship_decision_id
     AND d.subject_kind='edge'
     AND d.subject_id='noel_mark_translation_constraint:'||NEW.constraint_id::text
     AND d.action='ratify_canon_exclusion'
  ) THEN
   RAISE EXCEPTION 'A canon-excluded interpretation requires an exactly scoped ratified stewardship decision';
  END IF;
  IF NOT EXISTS (
   SELECT 1 FROM draft.noel_mark_translation_constraint_witnesses_v1 w
   WHERE w.constraint_id=NEW.constraint_id
     AND w.witness_role='canon_counterexample'
     AND EXISTS (
       SELECT 1 FROM draft.noel_mark_state_transition_observations_v1 t
       WHERE t.transition_id=w.transition_id AND t.identity_id=NEW.identity_id
       AND t.source_token_id=w.source_token_id
       AND t.observation_status='steward_reviewed'
       AND t.prior_state_key=NEW.before_state
       AND t.operation_key=NEW.governing_operation
       AND t.resulting_state_key IS DISTINCT FROM NEW.after_state
       AND t.observed_conditions @> NEW.condition_predicates
     )
  ) THEN
   RAISE EXCEPTION 'A canon-excluded interpretation requires a recorded canonical counterexample occurrence';
  END IF;
 END IF;
 RETURN NEW;
END;
$guard$;
CREATE TRIGGER noel_mark_translation_permission_guard_v1
BEFORE INSERT OR UPDATE ON draft.noel_mark_translation_constraints_v1
FOR EACH ROW EXECUTE FUNCTION draft.noel_mark_translation_permission_guard_v1();

-- State transitions are source-scoped *research observations*, never inferred
-- from an LXX lexical label. A different Greek word cannot supply a state.
CREATE TABLE draft.noel_mark_state_transition_observations_v1 (
 transition_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 identity_id text NOT NULL REFERENCES draft.noel_mark_identities(identity_id),
 witness_key text NOT NULL DEFAULT 'mt_noel_current' CHECK(witness_key='mt_noel_current'),
 source_token_id text NOT NULL,
 canonical_ref text NOT NULL CHECK(length(btrim(canonical_ref))>0),
 source_token_span_ids text[] NOT NULL DEFAULT ARRAY[]::text[],
 participant_key text, target_key text,
 prior_state_key text, operation_key text, resulting_state_key text,
 observed_conditions jsonb NOT NULL DEFAULT '{}'::jsonb
  CHECK(jsonb_typeof(observed_conditions)='object'),
 observation_status text NOT NULL DEFAULT 'candidate'
  CHECK(observation_status IN ('candidate','source_checked','steward_reviewed')),
 source_basis text NOT NULL CHECK(length(btrim(source_basis))>0),
 reviewed_by text,reviewed_at timestamptz,
 recorded_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(identity_id,source_token_id,canonical_ref,source_basis),
 CHECK(observation_status<>'steward_reviewed' OR
       (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);
CREATE INDEX noel_mark_transition_by_identity_v1
 ON draft.noel_mark_state_transition_observations_v1(identity_id,source_token_id);
ALTER TABLE draft.noel_mark_translation_constraint_witnesses_v1
 ADD COLUMN transition_id bigint REFERENCES
 draft.noel_mark_state_transition_observations_v1(transition_id);

CREATE FUNCTION draft.noel_mark_validate_transition_origin_v1()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path TO ''
AS $origin$
BEGIN
 IF NOT EXISTS (
  SELECT 1 FROM draft.noel_mark_occurrence_bindings o
  JOIN draft.noel_mark_identity_forms f ON f.form_id=o.form_id
  WHERE o.witness_key=NEW.witness_key AND o.source_token_id=NEW.source_token_id
  AND o.representation_rank='R2'
  AND o.representation_contract_key='mt_noel_current_exact_surface_v1'
  AND f.identity_id=NEW.identity_id
 ) THEN RAISE EXCEPTION 'State observation must bind a real source token and NMI'; END IF;
 RETURN NEW;
END;
$origin$;
CREATE TRIGGER noel_mark_validate_transition_origin_v1
BEFORE INSERT OR UPDATE ON draft.noel_mark_state_transition_observations_v1
FOR EACH ROW EXECUTE FUNCTION draft.noel_mark_validate_transition_origin_v1();

-- Read-only dry run. Only identical *specified* prior state, operation and
-- conditions can produce a counterexample candidate; never a prohibition.
CREATE FUNCTION draft.test_noel_mark_state_transition_v1(
 p_constraint_id bigint,p_transition_id bigint
) RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path TO ''
AS $test$
WITH matched AS (
 SELECT c.*,o.transition_id,o.source_token_id,o.canonical_ref,
 o.identity_id AS observed_identity,o.observation_status,
 o.prior_state_key,o.operation_key,o.resulting_state_key,o.observed_conditions,
 b.form_id
 FROM draft.noel_mark_translation_constraints_v1 c
 JOIN draft.noel_mark_state_transition_observations_v1 o
  ON o.transition_id=p_transition_id
 JOIN draft.noel_mark_occurrence_bindings b
  ON b.source_token_id=o.source_token_id AND b.witness_key=o.witness_key
  AND b.representation_rank='R2'
  AND b.representation_contract_key='mt_noel_current_exact_surface_v1'
 WHERE c.constraint_id=p_constraint_id
)
SELECT coalesce((
 SELECT jsonb_build_object(
 'found',true,'contract','song_canon_transition_dry_run_v1',
 'constraint_id',c.constraint_id,'transition_id',c.transition_id,
 'source_token_id',c.source_token_id,'canonical_ref',c.canonical_ref,
 'evaluation',CASE
 WHEN c.identity_id<>c.observed_identity THEN 'not_applicable'
 WHEN NOT (CASE c.scope_kind
   WHEN 'identity' THEN c.scope_ref=c.identity_id
   WHEN 'form' THEN c.scope_ref=c.form_id
   WHEN 'occurrence' THEN c.scope_ref=c.source_token_id
   WHEN 'state_transition' THEN c.scope_ref=c.transition_id::text
   ELSE false END) THEN 'not_applicable'
 WHEN c.before_state IS NULL OR c.governing_operation IS NULL OR
      c.after_state IS NULL OR c.prior_state_key IS NULL OR
      c.operation_key IS NULL OR c.resulting_state_key IS NULL
      THEN 'insufficient_state_evidence'
 WHEN NOT (c.observed_conditions @> c.condition_predicates) THEN 'conditions_not_matched'
 WHEN c.before_state<>c.prior_state_key OR
      c.governing_operation<>c.operation_key THEN 'different_input_or_operation'
 WHEN c.after_state=c.resulting_state_key THEN 'compatible_under_recorded_conditions'
 WHEN c.observation_status='steward_reviewed' THEN 'counterexample_candidate'
 ELSE 'counterexample_unreviewed'
 END,
 'proposed',jsonb_build_object('prior',c.before_state,'operation',c.governing_operation,'result',c.after_state,'conditions',c.condition_predicates),
 'observed',jsonb_build_object('prior',c.prior_state_key,'operation',c.operation_key,'result',c.resulting_state_key,'conditions',c.observed_conditions),
 'observation_status',c.observation_status,
 'authority_limit','Dry run only. Identical authored state labels do not prove semantic equivalence; contradictions are provisional; no Greek translation is banned automatically.'
 ) FROM matched c LIMIT 1
),jsonb_build_object('found',false,'contract','song_canon_transition_dry_run_v1'));
$test$;

ALTER TABLE draft.noel_mark_state_transition_observations_v1 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE draft.noel_mark_state_transition_observations_v1 FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION draft.test_noel_mark_state_transition_v1(bigint,bigint) FROM PUBLIC,anon,authenticated;

-- Private lookup augments the existing private source-token reader; it does not
-- edit source records, lexical Reality Pools or historical Strong's labels.
CREATE FUNCTION draft.get_noel_mark_translation_reality_v1(
 p_source_token_id text, p_limit integer DEFAULT 50
) RETURNS jsonb
LANGUAGE sql STABLE SECURITY INVOKER SET search_path TO ''
AS $function$
WITH origin AS (
 SELECT o.source_token_id,o.witness_key,o.form_id,i.identity_id,
        i.projected_surface
 FROM draft.noel_mark_occurrence_bindings o
 JOIN draft.noel_mark_identity_forms f ON f.form_id=o.form_id
  AND f.identity_contract_key='mt_noel_current_consonantal_projection_v1'
 JOIN draft.noel_mark_identities i ON i.identity_id=f.identity_id
 WHERE o.witness_key='mt_noel_current'
 AND o.representation_rank='R2'
 AND o.representation_contract_key='mt_noel_current_exact_surface_v1'
 AND o.source_token_id=btrim(p_source_token_id)
)
SELECT coalesce((
 SELECT jsonb_build_object(
  'contract','noel_mark_song_translation_reality_v1',
  'found',true,
  'source_token_id',o.source_token_id,
  'identity_id',o.identity_id,
  'form_id',o.form_id,
  'hebrew_consonants',o.projected_surface,
  'canonical_context',draft.get_noel_mark_occurrence_context_v1(o.source_token_id,12),
  'song_anchor_choices',(
    SELECT coalesce(jsonb_agg(jsonb_build_object(
      'anchor_id',x.anchor_id,'song_reference',x.song_canonical_ref,
      'greek_lexeme',x.greek_lexeme_key,'greek_surface',x.greek_surface,
      'song_anchor_state',x.song_anchor_state,
      'song_source_token_id',x.source_token_id,
      'lxx_token_id',x.greek_token_id) ORDER BY x.song_canonical_ref,x.anchor_id),'[]'::jsonb)
    FROM (
     SELECT a.anchor_id,a.song_canonical_ref,a.song_anchor_state,
      e.greek_lexeme_key,e.greek_surface,e.source_token_id,e.greek_token_id
     FROM draft.noel_mark_song_anchor_choices_v1 a
     JOIN draft.noel_mark_lxx_choice_occurrences_v1 e ON e.choice_id=a.choice_id
     WHERE a.identity_id=o.identity_id
     ORDER BY a.song_canonical_ref,a.anchor_id
     LIMIT 100
    ) x
  ),
  'this_occurrence_lxx_members',(
    SELECT coalesce(jsonb_agg(jsonb_build_object(
      'alignment_segment_id',x.alignment_segment_id,
      'greek_token_id',x.greek_token_id,'greek_surface',x.greek_surface,
      'greek_lexeme',x.greek_lexeme_key,
      'source_order',x.source_member_order,'target_order',x.target_member_order,
      'source_role',x.source_member_role,'target_role',x.target_member_role,
      'source_token_count',x.source_segment_count,'target_token_count',x.target_segment_count,
      'mapping_scope',x.mapping_scope,'evidence_quality',x.evidence_quality,
      'member_function',x.greek_member_function)
      ORDER BY x.alignment_segment_id,x.target_member_order,x.greek_token_id),'[]'::jsonb)
    FROM (
      SELECT e.* FROM draft.noel_mark_lxx_choice_occurrences_v1 e
      WHERE e.source_token_id=o.source_token_id AND e.identity_id=o.identity_id
      ORDER BY e.alignment_segment_id,e.target_member_order,e.greek_token_id
      LIMIT least(greatest(coalesce(p_limit,50),1),100)
    ) x
  ),
  'other_attested_lxx_choices',(
    SELECT coalesce(jsonb_agg(jsonb_build_object(
      'greek_lexeme',x.greek_lexeme_key,
      'source_occurrences',x.n,'sample_source_token_id',x.sample_id,
       'mapping_scope',x.mapping_scope,'greek_member_function',x.greek_member_function)
       ORDER BY x.n DESC,x.greek_lexeme_key),'[]'::jsonb)
    FROM (
     SELECT e.greek_lexeme_key,e.mapping_scope,e.greek_member_function,count(DISTINCT e.source_token_id) n,
     min(e.source_token_id) sample_id
     FROM draft.noel_mark_lxx_choice_occurrences_v1 e
     WHERE e.identity_id=o.identity_id AND
       e.source_token_id NOT LIKE 'tok.MT.Song.%'
     GROUP BY e.greek_lexeme_key,e.mapping_scope,e.greek_member_function
     ORDER BY count(DISTINCT e.source_token_id) DESC,e.greek_lexeme_key
     LIMIT least(greatest(coalesce(p_limit,50),1),100)
    ) x
  ),
  'translation_constraints',(
    SELECT coalesce(jsonb_agg(jsonb_build_object(
      'constraint_id',x.constraint_id,'greek_lexeme',x.candidate_greek_lexeme_key,
      'assessment',x.assessment_state,'scope_kind',x.scope_kind,'scope_ref',x.scope_ref,
      'test_basis',x.test_basis,'counterexample_basis',x.counterexample_basis,
      'before_state',x.before_state,'operation',x.governing_operation,
      'after_state',x.after_state,'conditions',x.condition_predicates,
      'stewardship_decision_id',x.stewardship_decision_id)
      ORDER BY x.constraint_id),'[]'::jsonb)
    FROM (
     SELECT c.* FROM draft.noel_mark_translation_constraints_v1 c
     WHERE c.identity_id=o.identity_id
       AND ((c.scope_kind='identity' AND c.scope_ref=o.identity_id)
          OR (c.scope_kind='form' AND c.scope_ref=o.form_id)
          OR (c.scope_kind='occurrence' AND c.scope_ref=o.source_token_id)
          OR c.scope_kind='state_transition')
     ORDER BY c.constraint_id
     LIMIT least(greatest(coalesce(p_limit,50),1),100)
    ) x
  ),
  'canonical_transition_observations',(
    SELECT coalesce(jsonb_agg(jsonb_build_object(
      'transition_id',x.transition_id,'reference',x.canonical_ref,'status',x.observation_status,
      'prior',x.prior_state_key,'operation',x.operation_key,'result',x.resulting_state_key)
      ORDER BY x.transition_id),'[]'::jsonb)
    FROM (SELECT tr.* FROM draft.noel_mark_state_transition_observations_v1 tr
      WHERE tr.source_token_id=o.source_token_id AND tr.identity_id=o.identity_id
      ORDER BY tr.transition_id LIMIT 20) x
  ),
  'authority_limit','Observed LXX choices are not permissions; an absent choice is not forbidden; Greek-sharing Hebrew marks are not identical; canonical exclusion requires the recorded state-transition proof and steward decision.'
 ) FROM origin o LIMIT 1
),jsonb_build_object('contract','noel_mark_song_translation_reality_v1',
 'found',false,'source_token_id',p_source_token_id));
$function$;

CREATE FUNCTION draft.get_noel_greek_to_hebrew_marks_v1(
 p_greek_lexeme_key text,p_limit integer DEFAULT 50
) RETURNS jsonb
LANGUAGE sql STABLE SECURITY INVOKER SET search_path TO ''
AS $function$
SELECT jsonb_build_object(
 'contract','noel_greek_to_hebrew_marks_v1',
 'greek_lexeme_key',p_greek_lexeme_key,
 'hebrew_marks',coalesce((
 SELECT jsonb_agg(jsonb_build_object(
   'identity_id',x.identity_id,'hebrew_consonants',x.projected_surface,
   'source_occurrences',x.n,'sample_source_token_id',x.example,
   'direct_token_attestations',x.direct_n,'phrase_memberships',x.phrase_n)
   ORDER BY x.n DESC,x.identity_id)
 FROM (
   SELECT e.identity_id,i.projected_surface,
     count(DISTINCT e.source_token_id) n,
     count(DISTINCT e.source_token_id) FILTER (WHERE e.mapping_scope='direct_token') direct_n,
     count(DISTINCT e.source_token_id) FILTER (WHERE e.mapping_scope<>'direct_token') phrase_n,
     min(e.source_token_id) example
   FROM draft.noel_mark_lxx_choice_occurrences_v1 e
   JOIN draft.noel_mark_identities i ON i.identity_id=e.identity_id
   WHERE e.greek_lexeme_key=btrim(p_greek_lexeme_key)
   GROUP BY e.identity_id,i.projected_surface
   ORDER BY n DESC,e.identity_id
   LIMIT least(greatest(coalesce(p_limit,50),1),100)
 ) x
 ),'[]'::jsonb),
 'authority_limit','A shared Greek translation does not merge Hebrew mark identities or prove a common state transition.'
);
$function$;

