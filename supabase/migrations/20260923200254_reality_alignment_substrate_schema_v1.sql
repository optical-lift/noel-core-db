
create table draft.reality_witness_registry (
  witness_key text primary key,
  witness_name text not null,
  witness_kind text not null,
  native_domain text,
  source_object_type text,
  source_object_id text,
  source_role text,
  provenance_status text not null default 'registered',
  is_active boolean not null default true,
  notes text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table draft.reality_witness_registry is
'Registry of sources, frameworks, instruments, corpora, practitioners, reports, and other witnesses that can contribute objects to one Reality Alignment space. Witness identity is preserved; registration does not merge witness ontologies.';

create unique index reality_witness_registry_source_uq
on draft.reality_witness_registry(source_object_type,source_object_id)
where source_object_type is not null and source_object_id is not null;

create table draft.reality_occurrences (
  occurrence_id bigint generated by default as identity primary key,
  occurrence_key text not null unique,
  occurrence_kind text not null,
  subject_ref_type text,
  subject_ref text,
  occurred_at timestamptz,
  captured_by_witness_key text references draft.reality_witness_registry(witness_key)
    on update cascade on delete set null,
  raw_summary text,
  raw_payload jsonb not null default '{}'::jsonb,
  occurrence_status text not null default 'captured',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table draft.reality_occurrences is
'An occurrence is the shared reality anchor around which multiple witnesses may align. It is not owned by any medical, spiritual, mechanical, emotional, or other disciplinary ontology.';

create table draft.reality_occurrence_coordinates (
  occurrence_coordinate_id bigint generated by default as identity primary key,
  occurrence_id bigint not null references draft.reality_occurrences(occurrence_id)
    on update cascade on delete cascade,
  coordinate_group_key text not null default 'root',
  dimension_key text not null references draft.reality_query_dimension_registry(dimension_key)
    on update cascade on delete restrict,
  dimension_value text not null,
  normalized_value text not null,
  coordinate_role text not null default 'feature',
  coordinate_order integer not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table draft.reality_occurrence_coordinates is
'Coordinate spine for an observed occurrence. Coordinates preserve local grouping independently of any witness explanation.';

create unique index reality_occurrence_coordinates_uq
on draft.reality_occurrence_coordinates(
  occurrence_id,coordinate_group_key,dimension_key,normalized_value
);

create index reality_occurrence_coordinates_lookup_idx
on draft.reality_occurrence_coordinates(dimension_key,normalized_value,occurrence_id);

create table draft.reality_alignment_segments (
  alignment_segment_id bigint generated by default as identity primary key,
  alignment_key text not null unique,
  occurrence_id bigint not null references draft.reality_occurrences(occurrence_id)
    on update cascade on delete cascade,
  alignment_kind text not null,
  relation_type text not null,
  alignment_status text not null default 'working',
  resolution_confidence text,
  review_status text not null default 'unreviewed',
  source_basis text,
  notes text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table draft.reality_alignment_segments is
'First-class bridge between an observed reality occurrence and one or more witness-native objects. The segment records contact/alignment without requiring object identity or ontology equivalence.';

create index reality_alignment_segments_occurrence_idx
on draft.reality_alignment_segments(occurrence_id,alignment_kind,relation_type);

create table draft.reality_alignment_members (
  alignment_member_id bigint generated by default as identity primary key,
  alignment_segment_id bigint not null references draft.reality_alignment_segments(alignment_segment_id)
    on update cascade on delete cascade,
  side text not null,
  witness_key text references draft.reality_witness_registry(witness_key)
    on update cascade on delete restrict,
  occurrence_coordinate_id bigint references draft.reality_occurrence_coordinates(occurrence_coordinate_id)
    on update cascade on delete cascade,
  object_type text,
  object_id text,
  member_role text not null,
  member_order integer not null default 0,
  resolution_status text not null default 'working',
  source_locator text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reality_alignment_members_side_check check (side in ('reality','witness')),
  constraint reality_alignment_members_shape_check check (
    (side='reality' and occurrence_coordinate_id is not null)
    or
    (side='witness' and witness_key is not null and object_type is not null and object_id is not null)
  )
);

comment on table draft.reality_alignment_members is
'Members of a Reality Alignment segment. Reality-side members point to occurrence coordinates; witness-side members point to native source objects and retain witness identity. One-to-one, one-to-many, many-to-one, and many-to-many alignments are all representable.';

create unique index reality_alignment_members_uq
on draft.reality_alignment_members(
  alignment_segment_id,
  side,
  coalesce(witness_key,''),
  coalesce(occurrence_coordinate_id,0),
  coalesce(object_type,''),
  coalesce(object_id,''),
  member_role
);

create index reality_alignment_members_coordinate_idx
on draft.reality_alignment_members(occurrence_coordinate_id)
where occurrence_coordinate_id is not null;

create index reality_alignment_members_object_idx
on draft.reality_alignment_members(object_type,object_id)
where object_type is not null and object_id is not null;

create table draft.reality_alignment_residue_registry (
