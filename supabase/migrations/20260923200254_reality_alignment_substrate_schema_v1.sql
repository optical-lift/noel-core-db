create view intelligence.v_reality_alignment_segment_evidence_v1
with (security_invoker=true)
as
select
  s.alignment_segment_id,
  s.alignment_key,
  s.occurrence_id,
  o.occurrence_key,
  s.alignment_kind,
  s.relation_type,
  s.alignment_status,
  s.resolution_confidence,
  s.review_status,
  s.source_basis,
  count(m.alignment_member_id) filter(where m.side='reality')::integer as reality_member_count,
  count(m.alignment_member_id) filter(where m.side='witness')::integer as witness_member_count,
  count(distinct m.witness_key) filter(where m.side='witness')::integer as witness_count,
  jsonb_agg(
    jsonb_build_object(
      'side',m.side,
      'witnessKey',m.witness_key,
      'witnessName',w.witness_name,
      'coordinateId',m.occurrence_coordinate_id,
      'objectType',m.object_type,
      'objectId',m.object_id,
      'memberRole',m.member_role,
      'memberOrder',m.member_order,
      'resolutionStatus',m.resolution_status,
      'sourceLocator',m.source_locator,
      'metadata',m.metadata
    )
    order by case when m.side='reality' then 0 else 1 end,m.member_order,m.alignment_member_id
  ) filter(where m.alignment_member_id is not null) as members,
  s.metadata,
  s.created_at,
  s.updated_at
from draft.reality_alignment_segments s
join draft.reality_occurrences o using(occurrence_id)
left join draft.reality_alignment_members m using(alignment_segment_id)
left join draft.reality_witness_registry w on w.witness_key=m.witness_key
group by
  s.alignment_segment_id,s.alignment_key,s.occurrence_id,o.occurrence_key,
  s.alignment_kind,s.relation_type,s.alignment_status,s.resolution_confidence,
  s.review_status,s.source_basis,s.metadata,s.created_at,s.updated_at;

comment on view intelligence.v_reality_alignment_segment_evidence_v1 is
'Cross-domain analogue of alignment-segment evidence: one reality anchor, native witness objects, and the explicit member structure of the bridge between them.';

create view intelligence.v_reality_occurrence_viewport_v1
with (security_invoker=true)
as
select
  o.occurrence_id,
  o.occurrence_key,
  o.occurrence_kind,
  o.subject_ref_type,
  o.subject_ref,
  o.occurred_at,
  o.raw_summary,
  o.occurrence_status,
  coalesce((
    select jsonb_agg(
      jsonb_build_object(
        'coordinateId',c.occurrence_coordinate_id,
        'groupKey',c.coordinate_group_key,
        'dimensionKey',c.dimension_key,
        'value',c.dimension_value,
        'normalizedValue',c.normalized_value,
        'role',c.coordinate_role,
        'order',c.coordinate_order
      )
      order by c.coordinate_group_key,c.coordinate_order,c.occurrence_coordinate_id
    )
    from draft.reality_occurrence_coordinates c
    where c.occurrence_id=o.occurrence_id
  ),'[]'::jsonb) as coordinates,
  coalesce((
    select jsonb_agg(
      jsonb_build_object(
        'alignmentSegmentId',a.alignment_segment_id,
        'alignmentKey',a.alignment_key,
        'alignmentKind',a.alignment_kind,
        'relationType',a.relation_type,
        'alignmentStatus',a.alignment_status,
        'resolutionConfidence',a.resolution_confidence,
        'reviewStatus',a.review_status,
        'sourceBasis',a.source_basis,
        'realityMemberCount',a.reality_member_count,
        'witnessMemberCount',a.witness_member_count,
        'witnessCount',a.witness_count,
        'members',a.members
      )
      order by a.alignment_segment_id
    )
    from intelligence.v_reality_alignment_segment_evidence_v1 a
    where a.occurrence_id=o.occurrence_id
  ),'[]'::jsonb) as alignments,
  coalesce((
    select jsonb_agg(
      jsonb_build_object(
        'residueId',r.residue_id,
        'coordinateId',r.occurrence_coordinate_id,
        'witnessKey',r.witness_key,
        'residueClass',r.residue_class,
        'disposition',r.disposition,
        'status',r.residue_status,
        'notes',r.notes,
        'metadata',r.metadata
      )
      order by r.residue_id
    )
    from draft.reality_alignment_residue_registry r
    where r.occurrence_id=o.occurrence_id
  ),'[]'::jsonb) as residue,
  o.metadata,
  o.created_at,
  o.updated_at
from draft.reality_occurrences o;

comment on view intelligence.v_reality_occurrence_viewport_v1 is
'Unified occurrence viewport. It composes coordinates, cross-witness alignments, and unresolved residue while preserving every witness as a separate source object.';

