comment on table draft.reality_alignment_residue_registry is
'Explicit registry for coordinates or witness material not accounted for by current alignments. Residue is preserved as information rather than forced into an existing explanation.';

create unique index reality_alignment_residue_uq
on draft.reality_alignment_residue_registry(
  occurrence_id,
  coalesce(occurrence_coordinate_id,0),
  coalesce(witness_key,''),
